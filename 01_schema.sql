DROP TABLE IF EXISTS order_items CASCADE;
DROP TABLE IF EXISTS orders CASCADE;
DROP TABLE IF EXISTS inventory CASCADE;
DROP TABLE IF EXISTS products CASCADE;
DROP TABLE IF EXISTS categories CASCADE;
DROP TABLE IF EXISTS suppliers CASCADE;
DROP TABLE IF EXISTS employees CASCADE;
DROP TABLE IF EXISTS customers CASCADE;

CREATE TABLE customers (
    customer_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name       VARCHAR(50) NOT NULL,
    last_name        VARCHAR(50) NOT NULL,
    email            VARCHAR(120) UNIQUE,
    phone            VARCHAR(20),
    city             VARCHAR(60),
    registration_date DATE NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT chk_customer_email CHECK (email IS NULL OR POSITION('@' IN email) > 1)
);

CREATE TABLE suppliers (
    supplier_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_name VARCHAR(100) NOT NULL,
    contact_name  VARCHAR(100),
    phone         VARCHAR(20),
    city          VARCHAR(60) NOT NULL,
    rating        NUMERIC(2,1) CHECK (rating BETWEEN 1.0 AND 5.0)
);

CREATE TABLE categories (
    category_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR(60) NOT NULL UNIQUE,
    description   VARCHAR(250)
);

CREATE TABLE employees (
    employee_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name  VARCHAR(50) NOT NULL,
    last_name   VARCHAR(50) NOT NULL,
    role        VARCHAR(50) NOT NULL,
    hire_date   DATE NOT NULL,
    city        VARCHAR(60)
);

CREATE TABLE products (
    product_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name VARCHAR(120) NOT NULL,
    category_id  INTEGER NOT NULL REFERENCES categories(category_id),
    supplier_id  INTEGER NOT NULL REFERENCES suppliers(supplier_id),
    unit_price   NUMERIC(10,2) NOT NULL CHECK (unit_price >= 0),
    cost_price   NUMERIC(10,2) NOT NULL CHECK (cost_price >= 0),
    is_active    BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT chk_product_margin CHECK (unit_price >= cost_price)
);

CREATE TABLE inventory (
    inventory_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id    INTEGER NOT NULL UNIQUE REFERENCES products(product_id) ON DELETE CASCADE,
    quantity_on_hand INTEGER NOT NULL DEFAULT 0 CHECK (quantity_on_hand >= 0),
    reorder_level INTEGER NOT NULL DEFAULT 10 CHECK (reorder_level >= 0),
    last_updated  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE orders (
    order_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INTEGER NOT NULL REFERENCES customers(customer_id),
    employee_id INTEGER REFERENCES employees(employee_id),
    order_date  DATE NOT NULL,
    order_status VARCHAR(20) NOT NULL DEFAULT 'Completed'
        CHECK (order_status IN ('Pending','Completed','Cancelled','Returned')),
    payment_method VARCHAR(20) NOT NULL
        CHECK (payment_method IN ('Cash','Card','UPI','Net Banking'))
);

CREATE TABLE order_items (
    order_item_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      INTEGER NOT NULL REFERENCES orders(order_id) ON DELETE CASCADE,
    product_id    INTEGER NOT NULL REFERENCES products(product_id),
    quantity      INTEGER NOT NULL CHECK (quantity > 0),
    unit_price    NUMERIC(10,2) NOT NULL CHECK (unit_price >= 0),
    discount_pct  NUMERIC(5,2) NOT NULL DEFAULT 0 CHECK (discount_pct BETWEEN 0 AND 100),
    CONSTRAINT uq_order_product UNIQUE (order_id, product_id)
);

CREATE INDEX idx_orders_order_date ON orders(order_date);
CREATE INDEX idx_orders_customer ON orders(customer_id);
CREATE INDEX idx_order_items_product ON order_items(product_id);
CREATE INDEX idx_products_category ON products(category_id);
